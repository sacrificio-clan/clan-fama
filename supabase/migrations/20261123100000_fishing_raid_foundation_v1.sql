-- SACRIFICIO RPG - Fishing raid foundation V1
-- Adds the 8-hour multi-fish fishing expedition model.
-- Run after 20261122160000_game_rpg_v1.sql and 20261122170000_game_save_v1.sql.
begin;

-- Each lake has exactly five species; each position represents one rarity tier.
alter table public.game_fishing_area_items
  add column if not exists rarity text not null default 'common';

alter table public.game_fishing_area_items
  drop constraint if exists game_fishing_area_items_rarity_check;
alter table public.game_fishing_area_items
  add constraint game_fishing_area_items_rarity_check
  check (rarity in ('common','uncommon','rare','epic','legendary'));

-- Existing catalog order maps the five species in each lake to five rarity tiers.
with ranked as (
  select area_id, fish_item_id,
         row_number() over (partition by area_id order by sort_order) as rarity_order
    from public.game_fishing_area_items
)
update public.game_fishing_area_items a
   set rarity = case ranked.rarity_order
     when 1 then 'common'
     when 2 then 'uncommon'
     when 3 then 'rare'
     when 4 then 'epic'
     when 5 then 'legendary'
     else 'common'
   end
  from ranked
 where ranked.area_id = a.area_id
   and ranked.fish_item_id = a.fish_item_id;

-- Config is data-driven. Odds and bait multipliers remain unset until game balance is approved.
create table if not exists public.game_fishing_rules (
  id smallint primary key default 1 check (id = 1),
  duration interval not null default interval '8 hours',
  fish_per_badge_per_hour integer not null default 1 check (fish_per_badge_per_hour > 0),
  special_hour_luck_multiplier numeric(8,3) not null default 2 check (special_hour_luck_multiplier >= 1),
  special_tag_chance numeric(5,4) not null default 0.25 check (special_tag_chance between 0 and 1),
  pity_batch_size integer not null default 50 check (pity_batch_size > 0),
  rarity_odds jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
insert into public.game_fishing_rules (id) values (1) on conflict (id) do nothing;

-- Bait changes only Luck; it never changes the number of fish.
alter table public.game_baits
  add column if not exists luck_multiplier numeric(8,3);
update public.game_baits
   set luck_multiplier = coalesce(luck_multiplier, luck_bonus)
 where luck_bonus is not null;

-- One active expedition per player remains enforced by the existing partial unique index.
alter table public.game_fishing_jobs
  alter column fish_item_id drop not null;
alter table public.game_fishing_jobs
  add column if not exists badge_count integer not null default 0 check (badge_count >= 0),
  add column if not exists base_fish_quantity integer not null default 0 check (base_fish_quantity >= 0),
  add column if not exists luck_multiplier numeric(8,3) not null default 1 check (luck_multiplier >= 1),
  add column if not exists collection_tag_id integer references public.game_tags(id),
  add column if not exists collected_at timestamptz,
  add column if not exists result_count integer not null default 0 check (result_count >= 0);

create table if not exists public.game_fishing_job_results (
  id bigint generated by default as identity primary key,
  job_id uuid not null references public.game_fishing_jobs(id) on delete cascade,
  player_id uuid not null references public.game_profiles(player_id) on delete cascade,
  fish_item_id integer not null references public.game_items(id) on delete restrict,
  quantity integer not null default 1 check (quantity > 0),
  tag_ids integer[] not null default '{}'::integer[],
  rarity text not null check (rarity in ('common','uncommon','rare','epic','legendary')),
  pity_replacement boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists game_fishing_job_results_player_idx
  on public.game_fishing_job_results (player_id, created_at desc);
create index if not exists game_fishing_job_results_job_idx
  on public.game_fishing_job_results (job_id);

alter table public.game_fishing_rules enable row level security;
revoke all on table public.game_fishing_rules from anon, authenticated;
grant select on table public.game_fishing_rules to authenticated;
drop policy if exists game_fishing_rules_read on public.game_fishing_rules;
create policy game_fishing_rules_read on public.game_fishing_rules
  for select to authenticated using (true);

alter table public.game_fishing_job_results enable row level security;
revoke all on table public.game_fishing_job_results from anon, authenticated;
grant select on table public.game_fishing_job_results to authenticated;
drop policy if exists game_fishing_results_read_own on public.game_fishing_job_results;
create policy game_fishing_results_read_own on public.game_fishing_job_results
  for select to authenticated using (player_id = auth.uid());
grant all on table public.game_fishing_job_results to service_role;

commit;

